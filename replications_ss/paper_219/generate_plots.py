    ax1.set_ylim(0, 30)
    ax1.grid(True, linestyle=':', alpha=0.6)
    ax1.axvline(-90, color='gray', linestyle='--', alpha=0.5)
    ax1.axvline(0, color='gray', linestyle='--', alpha=0.5)

