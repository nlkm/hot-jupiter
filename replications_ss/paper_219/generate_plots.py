    ax2.grid(True, linestyle=':', alpha=0.6)
    ax2.legend(loc='lower left', framealpha=0.9, fontsize=8.5)
    ax2.set_title(r'(b) Basal Ductile Layer Viscoelastic Heating Focus')

    # 2(c): Maxwell Dissipation Factor vs Viscosity & Resonance Curve
    ax3 = fig.add_subplot(gs[1, 0])
    eta_log = np.linspace(10, 17, 200)
    eta_arr = 10.0**eta_log
    mu = 3.5e9
    n = 5.307e-5
    tau_arr = eta_arr / mu
    wt_arr = n * tau_arr
    D_arr = wt_arr / (1.0 + wt_arr**2)

    ax3.plot(eta_log,
             D_arr,
             color='#2ca02c',
             lw=2.2,
             label=r'Maxwell Dissipation Factor $D(\omega \tau_M)$')
    eta_opt_log = np.log10(mu / n)  # ~ 13.82
    ax3.axvline(
        eta_opt_log,
        color='red',
        linestyle='--',
        lw=1.5,
        label=
        r'Maxwell Peak $\eta_{\mathrm{opt}} = \mu/n = 6.6 \times 10^{13}\ \mathrm{Pa\ s}$'
    )
    ax3.axvline(13.0,
                color='#1f77b4',
                linestyle=':',
                lw=1.5,
                label=r'Basal Ice Viscosity $\eta_0 = 10^{13}\ \mathrm{Pa\ s}$')
    ax3.scatter([eta_opt_log], [0.5], color='red', s=60, zorder=5)

    ax3.set_xlabel(
        r'$\log_{10}(\text{Ice Viscosity } \eta\ [\mathrm{Pa\cdot s}])$')
    ax3.set_ylabel(
        r'Dissipation Metric $D(\omega \tau_M) = \frac{\omega \tau_M}{1 + (\omega \tau_M)^2}$'
    )
    ax3.set_xlim(10, 17)
    ax3.set_ylim(0, 0.55)
    ax3.grid(True, linestyle=':', alpha=0.6)
    ax3.legend(loc='upper right', framealpha=0.9, fontsize=8)
    ax3.set_title(r'(c) Maxwell Rheological Resonance Curve')

    # 2(d): Libration Decoupled vs Coupled Solid Moon Sensitivity
    ax4 = fig.add_subplot(gs[1, 1])
    d_sweep = sens_df['d_mean_km']
    p_dec = sens_df['p_total_decoupled_gw']
    p_coup = sens_df['p_total_coupled_gw']
    sens_df['f_spt_mw_m2']

    ax4.plot(d_sweep,
             p_dec,
             color='#9467bd',
             lw=2.2,
             label=r'Decoupled Shell (with Ocean): $P_{\mathrm{total}}$')
    ax4.plot(
        d_sweep,
        p_coup,
        color='#7f7f7f',
        lw=2.0,
        linestyle='--',
        label=
        r'Coupled Solid Moon (No Ocean): $P_{\mathrm{solid}} \approx 4.3\ \mathrm{GW}$'
    )
    ax4.axhspan(15.8 - 3.1,
                15.8 + 3.1,
                color='#ff7f0e',
                alpha=0.18,
                label=r'Cassini CIRS Obs ($15.8 \pm 3.1\ \mathrm{GW}$)')
    ax4.axvline(20.0,
                color='black',
                linestyle=':',
                lw=1.2,
                label=r'Nominal $d_{\mathrm{mean}} = 20\ \mathrm{km}$')

    ax4.set_xlabel(r'Global Mean Ice Shell Thickness $d_{\mathrm{mean}}$ [km]')
    ax4.set_ylabel(r'Total Tidal Dissipation Power [GW]')
    ax4.set_xlim(5, 45)
    ax4.set_ylim(0, 45)
    ax4.grid(True, linestyle=':', alpha=0.6)
    ax4.legend(loc='upper right', framealpha=0.9, fontsize=8)
    ax4.set_title(r'(d) Decoupled Ocean vs Solid-Body Libration Sensitivity')

    fig.suptitle(
        r'\textbf{Physical Sensitivity \& Rheological Regimes of Enceladus Ice Shell}',
        fontsize=13.5,
        y=0.98)
    pdf_path = os.path.join(output_dir, 'fig_model_choices.pdf')
