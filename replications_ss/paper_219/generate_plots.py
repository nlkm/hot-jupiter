def load_csv_data(filepath):
    data = {}
    with open(filepath, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            for k, v in row.items():
                if k not in data:
                    data[k] = []
                try:
                    data[k].append(float(v))
                except ValueError:
                    data[k].append(v)
    for k, val_list in data.items():
        if len(val_list) > 0 and isinstance(val_list[0], float):
            data[k] = np.array(val_list)
    return data


# Load CSV data generated by C++ engine
