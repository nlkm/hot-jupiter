    ax1_twin.plot(lat_df['latitude_deg'],
                  lat_df['total_heat_flux_mw_m2'],
                  color=color_f,
                  lw=2.2,
                  linestyle='-',
                  label=r'Total Heat Flux $F(\phi)$')
    ax1_twin.plot(lat_df['latitude_deg'],
                  lat_df['conductive_flux_mw_m2'],
                  color='#ff7f0e',
                  lw=1.6,
                  linestyle='--',
                  label=r'Conductive Flux $F_{\mathrm{cond}}$')
    ax1_twin.scatter([-85.0], [185.0],
                     color='#d62728',
                     s=60,
                     zorder=5,
                     marker='s',
                     label='Cassini CIRS SPT Obs (Howett 2011)')
